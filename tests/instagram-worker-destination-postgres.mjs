import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const require = createRequire(
  resolve(process.env.INTELLIGENCE_PG_TEST_DEPS || ".", "package.json"),
);
const { PGlite } = require("@electric-sql/pglite");
const db = new PGlite();
const oldOrigin = "https://mausehot.lovable.app";
const newOrigin = "https://preview.example.test";
const jobs = async () => (await db.query("select * from cron.job order by jobid")).rows;

try {
  // pg_cron and the original Vault activation are external to this migration.
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema cron; create schema private;
    create table cron.job(
      jobid bigint primary key generated by default as identity,
      jobname text unique, schedule text, command text, active boolean default true
    );
    create function cron.schedule(jobname text,schedule text,command text)
      returns bigint language sql as $$
        insert into cron.job(jobname,schedule,command) values ($1,$2,$3) returning jobid
      $$;
    create function cron.alter_job(job_id bigint,command text,active boolean)
      returns void language sql as $$ update cron.job set command=$2,active=$3 where jobid=$1 $$;
    create function public.enable_instagram_worker() returns boolean
      language sql security definer set search_path='' as $$select true$$;
    insert into cron.job(jobname,schedule,command) values
      ('00duhot-instagram-worker','* * * * *','${oldOrigin}/api/instagram/worker'),
      ('00duhot-instagram-analytics','* * * * *','${oldOrigin}/api/instagram/worker?job=analytics'),
      ('unrelated','0 * * * *','unrelated');
  `);
  const before = await jobs();
  await db.exec(
    await readFile(
      new URL(
        "../supabase/migrations/20261120150000_configurable_instagram_worker_origin.sql",
        import.meta.url,
      ),
      "utf8",
    ),
  );
  assert.deepEqual(await jobs(), before);
  await assert.rejects(
    db.query("select private.configure_instagram_worker_destination($1)", [
      "https://example.test/api",
    ]),
    /Expected an HTTPS origin/,
  );
  await db.exec("set role service_role");
  assert.equal(
    (await db.query("select public.enable_instagram_worker() active")).rows[0].active,
    true,
  );
  await db.exec("reset role");

  await db.query("select private.configure_instagram_worker_destination($1)", [newOrigin]);
  const paused = await jobs();
  assert.equal(paused.length, 3);
  assert.deepEqual(paused[2], before[2]);
  for (const row of paused.slice(0, 2)) {
    assert.equal(row.active, false);
    assert.match(row.command, /https:\/\/preview\.example\.test\/api\/instagram\/worker/);
    assert.doesNotMatch(row.command, /lovable\.app/);
    assert.match(row.command, /vault\.decrypted_secrets/);
  }
  assert.match(paused[0].command, /'Bearer '/);
  assert.match(paused[1].command, /\?job=analytics/);
  assert.match(paused[1].command, /'Analytics '/);
  await db.exec("set role service_role");
  assert.equal(
    (await db.query("select public.enable_instagram_worker() active")).rows[0].active,
    false,
  );
  await assert.rejects(
    db.query("select private.configure_instagram_worker_destination($1,true)", [newOrigin]),
    /permission denied/,
  );
  await db.exec("reset role");
  await db.query("select private.configure_instagram_worker_destination($1,true)", [newOrigin]);
  const running = await jobs();
  assert.deepEqual(
    running.slice(0, 2).map((j) => j.active),
    [true, true],
  );
  await db.query("select private.configure_instagram_worker_destination($1,true)", [newOrigin]);
  assert.deepEqual(await jobs(), running);
  console.log(
    "PASS: worker and analytics switch destination together, staging stays paused, unrelated jobs are preserved.",
  );
} finally {
  await db.close();
}
